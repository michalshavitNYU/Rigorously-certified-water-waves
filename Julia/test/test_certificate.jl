# ---------------------------------------------------------------------------
# Helpers: parse a `def name : ℚ := (p : ℚ) / q` or `def name : ℚ := p` line
# back to a Rational{BigInt}, so we can verify the emitted constants without
# having to actually run Lean.
# ---------------------------------------------------------------------------

"""
    parse_lean_rat_def(text, name) -> Rational{BigInt}

Find a line of the form
    def NAME : ℚ := ...
in `text`, parse the right-hand side as a Lean ℚ literal, and return the
corresponding `Rational{BigInt}`. Supports:
  - bare integer:       `def x : ℚ := 0`            → 0//1
  - bare negative int:  `def x : ℚ := -42`          → -42//1
  - parenthesised form: `def x : ℚ := ((p : ℚ) / q)` → p//q
Throws if the definition is not found or has an unexpected RHS.
"""
function parse_lean_rat_def(text::AbstractString, name::AbstractString)::Rational{BigInt}
    # Match: def <name> : ℚ := <rhs>\n
    # Anchor on `def name : ℚ := ` and capture the rest of the line.
    pat = Regex("def\\s+" * name * "\\s*:\\s*ℚ\\s*:=\\s*([^\\n]+)")
    m = match(pat, text)
    m === nothing && error("definition `def $name : ℚ := …` not found")
    rhs = strip(m.captures[1])

    # Try the parenthesised form first.
    pat_pq = r"^\(\(\s*(-?\d+)\s*:\s*ℚ\s*\)\s*/\s*(\d+)\s*\)$"
    mp = match(pat_pq, rhs)
    if mp !== nothing
        p = parse(BigInt, mp.captures[1])
        q = parse(BigInt, mp.captures[2])
        return Rational{BigInt}(p, q)
    end

    # Fall back to a bare integer (positive or negative).
    pat_int = r"^(-?\d+)$"
    mi = match(pat_int, rhs)
    if mi !== nothing
        return Rational{BigInt}(parse(BigInt, mi.captures[1]))
    end

    error("could not parse RHS of `$name`: `$rhs`")
end

# ---------------------------------------------------------------------------
# T7.1 — Basic M5 Stokes round-trip
# ---------------------------------------------------------------------------

@testset "T7.1 — emit_certificate: M5 Stokes case" begin
    y_coeffs = [-0.15^2/2, 0.15, 0.15^2]
    μ = 1 + 0.15^2
    β = 0.0

    text = emit_certificate(y_coeffs, μ, β;
                            M_order=4, N_grid=256, prec=128)

    @test !isempty(text)

    # Header sentinels.
    @test occursin("Auto-generated by BabenkoRigorous.jl", text)
    @test occursin("namespace WaveCAP.Certificate", text)
    @test occursin("end WaveCAP.Certificate", text)

    # Phase-6 format: the generated file must emit NO `axiom` declarations
    # (the trust anchors are theorems in CertificateAxioms.lean; a same-named
    # axiom here would collide). Commented `--   axiom …` references are fine.
    @test !occursin(r"(?:^|\n)axiom ", text)

    # Mandatory β=0 fields (the minimal scalar set).
    for field in ("N_cert", "a_cert", "μ_cert", "β_cert",
                  "N_fft_cert", "M_order_cert", "ε₀_cert")
        @test occursin("def $field", text)
    end

    # β = 0 ⇒ no capillary fields.
    @test !occursin("def DLower_cert", text)

    # Intermediate-quantity fields that were in earlier drafts must NOT be
    # in the certificate (the trust chain — Lean-verified universal lemmas +
    # Arb correctness — justifies the final ε₀_cert without per-grid-point
    # data, sup_bounds vectors, or Gpp/Gppp).
    for field in ("sup_bounds_y_cert", "sup_bounds_yu_cert", "sup_bounds_Hyu_cert",
                  "Gpp_bound_yyu_cert", "Gppp_bound_yyu_cert",
                  "R_jk_grid_cert", "R_jk_grid_cert_flat",
                  "top_sup_bound_R_cert",
                  "sup_bounds_G_cert", "Gpp_bound_G_cert", "Gppp_bound_G_cert")
        @test !occursin("def $field", text)
    end

    # Parse ε₀_cert back out and check the Stokes-case bound is ≤ 0.05.
    # (the ℚ-typed def is `ε₀_cert_ℚ`; the bare `ε₀_cert` is its ℝ view.)
    ε₀_rat = parse_lean_rat_def(text, "ε₀_cert_ℚ")
    println("T7.1 ε₀_cert (rational) ≈ ", Float64(ε₀_rat))
    @test ε₀_rat > 0
    @test Float64(ε₀_rat) ≤ 0.05

    # The certificate's ε₀ should match (be ≥) the Arb upper bound from
    # residual_bound at the same parameters.
    b = residual_bound(y_coeffs, μ, 0.0; M_order=4, N_grid=256, prec=128)
    @test Float64(ε₀_rat) ≥ Float64(Arblib.ubound(b)) * (1 - 1e-15)
end

