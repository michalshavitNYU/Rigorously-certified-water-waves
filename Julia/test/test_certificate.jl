# T7.2 — Determinism: emitting twice gives byte-identical output
# ---------------------------------------------------------------------------

@testset "T7.2 — emit_certificate is deterministic" begin
    y_coeffs = [-0.15^2/2, 0.15, 0.15^2]
    μ = 1 + 0.15^2

    text_a = emit_certificate(y_coeffs, μ, 0.0; M_order=4, N_grid=256, prec=128)
    text_b = emit_certificate(y_coeffs, μ, 0.0; M_order=4, N_grid=256, prec=128)
    @test text_a == text_b
end

# ---------------------------------------------------------------------------
# T7.3 — write_certificate writes the same bytes as emit_certificate returns
# ---------------------------------------------------------------------------

@testset "T7.3 — write_certificate round-trip" begin
    y_coeffs = [-0.15^2/2, 0.15, 0.15^2]
    μ = 1 + 0.15^2

    text_mem = emit_certificate(y_coeffs, μ, 0.0; M_order=4, N_grid=256, prec=128)

    mktempdir() do dir
        path = joinpath(dir, "Certificate.lean")
        text_ret = write_certificate(path, y_coeffs, μ, 0.0;
                                     M_order=4, N_grid=256, prec=128)
        @test isfile(path)
        text_disk = read(path, String)
        @test text_ret == text_mem
        @test text_disk == text_mem
    end
end

# ---------------------------------------------------------------------------
# T7.4 — arb_upper_rational / arb_lower_rational basic invariants
# ---------------------------------------------------------------------------

@testset "T7.4 — arb_*_rational invariants" begin
    # ub_rat ≥ ubound, lb_rat ≤ lbound (literal endpoint match)
    x = Arb("0.1"; prec=128)
    ub_rat = arb_upper_rational(x)
    lb_rat = arb_lower_rational(x)
    @test lb_rat ≤ ub_rat
    @test Float64(ub_rat) ≥ Float64(Arblib.ubound(x))
    @test Float64(lb_rat) ≤ Float64(Arblib.lbound(x))

    # Zero / negative
    @test arb_upper_rational(Arb(0; prec=128)) == 0
    @test arb_lower_rational(Arb(0; prec=128)) == 0
    @test arb_upper_rational(Arb(-2.5; prec=128)) == -5//2

    # Float64 midpoint should reproduce the float exactly.
    @test arb_midpoint_rational(Arb(0.1; prec=128)) == Rational{BigInt}(0.1)
end

# ---------------------------------------------------------------------------
# T7.5 — β ≠ 0 certificate has capillary fields
# ---------------------------------------------------------------------------

@testset "T7.5 — emit_certificate: β ≠ 0 has DLower_cert (only)" begin
    ε = 0.05
    β = 0.05
    μ = β + 1.0          # linear-dispersion choice
    y_coeffs = [0.0, ε]

    text = emit_certificate(y_coeffs, μ, β;
                            M_order=4, N_grid=256, prec=128)

    @test !isempty(text)

    # β≠0 adds exactly one field: DLower_cert.  Intermediate sup_bounds_G_cert,
    # Gpp_bound_G_cert, Gppp_bound_G_cert are NOT shipped — Lean's universal
    # Faà di Bruno + Fourier-tail lemmas justify the chain that produced ε₀_cert.
    @test occursin("def DLower_cert", text)
    for field in ("sup_bounds_G_cert", "Gpp_bound_G_cert", "Gppp_bound_G_cert")
        @test !occursin("def $field", text)
    end

    # β = 0.05 → β_cert literal should be the exact Float64 dyadic of 0.05.
    β_rat = parse_lean_rat_def(text, "β_cert_ℚ")
    @test β_rat == Rational{BigInt}(0.05)
    @test Float64(β_rat) == 0.05

    # DLower_cert should be a positive rational and ≤ 1 + ε.
    DLower_rat = parse_lean_rat_def(text, "DLower_cert_ℚ")
    @test DLower_rat > 0
    @test Float64(DLower_rat) ≤ 1.0 + ε
    println("T7.5 DLower_cert ≈ ", Float64(DLower_rat))
end

# ---------------------------------------------------------------------------
# T7.6 — Certificate ε₀ is a true upper bound (sanity vs residual_bound)
# ---------------------------------------------------------------------------

@testset "T7.6 — ε₀_cert ≥ certified Arb upper bound" begin
    cases = [
        ([-0.10^2/2, 0.10, 0.10^2], 1 + 0.10^2, 0.0,  4),
        ([-0.05^2/2, 0.05, 0.05^2], 1 + 0.05^2, 0.0,  4),
        ([0.0, 0.05],               0.05 + 1.0, 0.05, 4),
    ]
    for (y_coeffs, μ, β, M) in cases
        text = emit_certificate(y_coeffs, μ, β;
                                M_order=M, N_grid=256, prec=128)
        ε₀_rat = parse_lean_rat_def(text, "ε₀_cert_ℚ")

        b = residual_bound(y_coeffs, μ, β; M_order=M, N_grid=256, prec=128)
        ub = Arblib.ubound(b)

        # ε₀_cert should be ≥ the Arb upper-bound endpoint. Strict equality in
        # exact dyadic rationals: arb_upper_rational(b) == Rational(BigFloat(ub)).
        # In Float64 this should round-trip exactly.
        @test Float64(ε₀_rat) ≥ Float64(ub) * (1 - 1e-15)
    end
end
